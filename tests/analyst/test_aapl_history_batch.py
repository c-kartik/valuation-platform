    def test_exact_frozen_identities_and_seventy_slots(self):
        manifest=json.loads((ROOT/'docs/phase1-selected-filing-identity-manifest.json').read_text())
        selected=[r['identity'] for r in manifest['rows'] if r['ticker']=='AAPL']
        self.assertEqual([r['identity'] for r in self.rows],selected)
        self.assertEqual([r['identity']['annual_end'] for r in self.rows],['2021-09-25','2022-09-24','2023-09-30','2024-09-28','2025-09-27'])
        self.assertEqual(self.review['family_slots'],70)
        for r in self.rows:
            self.assertEqual([v['field'] for v in r['family_checklist']],[f.value for f in Field])
            self.assertFalse(r['analyst_complete']);self.assertFalse(r['new_assumptions_active'])
        self.assertEqual(self.review['outcomes'],dict(SOURCE_SUPPORTED=27,EXISTING_SCOPED_APPROVAL=8,PROPOSED_PENDING_APPROVAL=35,ESSENTIAL_EVIDENCE_EXCEPTION=0))

    def test_exact_selected_statement_values_not_assembled_expectations(self):
        # Literal selected income/cash-flow statement points, not assembly output.
        wanted=[(365817,108949,104038,11085,11284),(394328,119437,122151,10708,11104),
            (383285,114301,110543,10959,11519),(391035,123216,118254,9447,11445),(416161,133050,111482,12715,11698)]
        for r,values in zip(self.rows,wanted):
            self.assertEqual(tuple(Decimal(r['facts'][k]['value'])/1000000 for k in ['revenue','ebit','NetCashProvidedByUsedInOperatingActivities','PaymentsToAcquirePropertyPlantAndEquipment','DepreciationDepletionAndAmortization']),values)
            self.assertEqual(r['cash_signs']['PaymentsToAcquirePropertyPlantAndEquipment'],-1)
            self.assertEqual(r['cash_signs']['IncomeTaxesPaidNet'],-1)
            for k in ('revenue','ebit'):
                f=r['facts'][k];self.assertTrue(f['occurrences']);self.assertEqual(f['unit'],'USD')
                self.assertTrue(all(o['start']==r['identity']['annual_start'] and o['end']==r['identity']['annual_end'] and not o['dimensions'] for o in f['occurrences']))

    def test_independent_displays_and_accession_specific_reclassifications(self):
        self.assertEqual([len(r['cfo_reconciliation']['terms']) for r in self.rows],[12,12,10,10,10])
        self.assertEqual([len(r['movement_rows']) for r in self.rows],[7,7,6,6,6])
        for r in self.rows:
            cf=r['cfo_reconciliation'];self.assertTrue(cf['supported']);self.assertFalse(cf['residual_used'])
            self.assertEqual(sum(Decimal(t['contribution_usd']) for t in cf['terms']),Decimal(r['facts']['NetCashProvidedByUsedInOperatingActivities']['value']))
            display=next(p['exact_excerpt'] for p in r['passages'] if p['marker']=='independently_displayed_cfo')
            self.assertIn('Adjustments to reconcile',display);self.assertIn('Cash generated by operating activities',display)
            self.assertTrue(all(t['already_in_reported_cfo'] and t['not_book_delta_nwc'] for t in r['movement_rows']))
            self.assertFalse(r['additional_movement_deduction_permitted']);self.assertFalse(r['complete_nwc_required_for_proposed_path'])
        self.assertEqual([self.rows[i]['facts']['deferred_cfo']['value'] for i in [0,1]],['-4774000000','895000000'])
        self.assertTrue(all('deferred_cfo' not in r['facts'] for r in self.rows[2:]))

    def test_da_proxy_is_inactive_not_residual_amortization_or_msft_assumption(self):
        for r,value in zip(self.rows,['9500','8700','8500','8200','8000']):
            self.assertEqual(Decimal(r['facts']['depreciation_expense']['value'])/1000000,Decimal(value))
            proxy=r['proposed_da_proxy'];self.assertEqual(proxy['value_usd'],r['facts']['DepreciationDepletionAndAmortization']['value'])
            self.assertEqual(proxy['origin'],'proxy');self.assertFalse(proxy['accepted']);self.assertEqual(proxy['status'],p.PROPOSED)
            self.assertIsNone(proxy['expense_basis_da']);self.assertIsNone(proxy['finance_amortization_inclusion_assumption'])
            self.assertIsNone(proxy['inventory_lease_timing_bridge']);self.assertEqual(proxy['precision'],'-6')
            self.assertEqual(r['facts']['depreciation_expense']['precision'],'-8')
        self.assertTrue(all(any('Depreciation and amortization expense' in x['exact_excerpt'] for x in r['passages']) for r in self.rows[:2]))
        self.assertIsNone(self.result['accepted_view']['complete_expense_basis_da']['value'])

    def test_borrowing_bridge_scope_precision_and_overlap(self):
        named=[125567,121010,112112,107525,99887];carrying=[118719,110087,105103,96662,90678]
        for r,total,term in zip(self.rows,named,carrying):
            c={c['input_id']:c for c in r['calculations']}
            self.assertEqual(Decimal(c['named_financing']['value'])/1000000,total)
            self.assertEqual(Decimal(c['term_carrying']['value'])/1000000,term)
            self.assertEqual(sum(Decimal(x['contribution_usd']) for x in r['term_carrying_bridge']['terms']),Decimal(term)*1000000)
            self.assertEqual(c['named_financing']['operands'],['cp','current_debt','long_debt','finance_total'])
            self.assertNotIn('op_total',c['named_financing']['operands']);self.assertIsNone(r['supporting_unknowns']['additional_borrowing'])
        conflict=next(e for e in self.rows[0]['exceptions'] if e['input_id']=='principal')
        self.assertEqual({Decimal(x['raw_value']) for x in conflict['alternatives']},{Decimal('118100000000'),Decimal('118063000000')})
        self.assertNotIn('principal',self.rows[0]['facts'])
        self.assertEqual(self.rows[0]['term_carrying_bridge']['terms'][2]['multiplier'],1)
        self.assertEqual(self.rows[1]['term_carrying_bridge']['terms'][2]['multiplier'],-1)

